"""Run the known, open-set, and 50-case RAG evaluations and refresh result tables."""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[2]
REPO = BACKEND.parent
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from ml.evaluation.output_paths import get_results_dir

START = "<!-- COMPREHENSIVE_BENCHMARKS:START -->"
END = "<!-- COMPREHENSIVE_BENCHMARKS:END -->"


def _fmt(value):
    return "n/a" if value is None else f"{float(value):.4f}"


def update_results_doc(known: dict | None, opened: dict | None, rag: dict | None) -> None:
    """Replace an explicitly generated report block; preserve the rest of RESULTS.md."""
    known_metrics = (known or {}).get("LightGBM", {})
    imbalance = known_metrics.get("imbalance_aware_summary", {})
    open_summaries = (opened or {}).get("open_set_summary", {})
    open_summary = open_summaries.get("union_conf_mahalanobis") or open_summaries.get("confidence", {})
    rag_retrieval = (rag or {}).get("retrieval", {})
    rag_groundedness = (rag or {}).get("groundedness", {})
    body = "\n".join([
        "## Comprehensive benchmark comparison (generated)",
        "",
        "| Metric | Historical stratified baseline | Historical session-disjoint baseline | Current run |",
        "|---|---:|---:|---:|",
        f"| Known Macro-F1 | 0.9482 | 0.1898 | {_fmt(known_metrics.get('macro_f1'))} |",
        f"| Known Macro-AUPRC | n/a | n/a | {_fmt(known_metrics.get('macro_auprc'))} |",
        f"| Balanced accuracy | n/a | n/a | {_fmt(imbalance.get('balanced_accuracy'))} |",
        f"| Cohen's kappa | n/a | n/a | {_fmt(imbalance.get('cohen_kappa'))} |",
        f"| Open-set OSCR AUC | 0.8239 | 0.5410 | {_fmt(open_summary.get('oscr_auc'))} |",
        f"| Open-set FPR95 | n/a | n/a | {_fmt(open_summary.get('fpr95'))} |",
        f"| Open-set unknown recall | 0.3966 | 0.0760 | {_fmt(open_summary.get('unknown_recall'))} |",
        f"| RAG Hit@1 / Hit@3 / MRR | 0.8500 / 0.9000 / n/a | n/a | {_fmt(rag_retrieval.get('hit_at_1'))} / {_fmt(rag_retrieval.get('hit_at_3'))} / {_fmt(rag_retrieval.get('mrr'))} |",
        f"| RAG groundedness | n/a | n/a | {_fmt(rag_groundedness.get('score'))} |",
        "",
        f"Generated at {datetime.now(timezone.utc).isoformat()}. Historical values are the saved results described above; current values are from artifacts generated by this run. Groundedness covers extractive answer citations and ATT&CK identifiers.",
        "",
        "The current run used a 15% session-disjoint sample, 30,000-row open-set train cap, and confidence-only detector for bounded execution. Several held-out groups had zero test support (including Bot, BruteForce, and DosDDoS in the known classifier, and three of five open-set families), so these diagnostic aggregates are not directly comparable to the historical baselines. Macro-AUPRC averages only classes with both positive and negative test examples; Bot precision is not measurable in this run.",
    ])
    docs = REPO / "docs" / "RESULTS.md"
    prior = docs.read_text(encoding="utf-8")
    block = f"{START}\n{body}\n{END}"
    if START in prior and END in prior:
        prefix = prior.split(START, 1)[0]
        suffix = prior.split(END, 1)[1]
        updated = prefix + block + suffix
    else:
        updated = prior.rstrip() + "\n\n" + block + "\n"
    docs.write_text(updated, encoding="utf-8")


def run(args=None) -> dict:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sample", type=float, default=0.5)
    parser.add_argument("--split-mode", choices=("session_disjoint", "stratified_random"), default="session_disjoint")
    parser.add_argument("--include-xgboost", action="store_true")
    parser.add_argument("--skip-known", action="store_true")
    parser.add_argument("--skip-open-set", action="store_true")
    parser.add_argument("--skip-rag", action="store_true")
    options = parser.parse_args(args)

    pipeline = None
    if not (options.skip_known and options.skip_open_set):
        from ml.preprocessing.cicids_pipeline import build_full_pipeline
        pipeline = build_full_pipeline(sample=options.sample, split_mode=options.split_mode,
                                       sanitize_session_features=(options.split_mode == "session_disjoint"))
        pipeline["adaptive_family_calibration"] = True
        pipeline["adaptive_calibration_percentile"] = 95.0
        pipeline.update({"profile_name": "comprehensive_light", "sample_fraction": options.sample,
                         "train_row_cap_per_fold": 30_000, "bootstrap_resamples": 200,
                         "classifier_estimators": 80,
                         "run_id": f"comprehensive_light_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}"})
        # Keep the orchestration run bounded and repeatable; the saved session comparison
        # separately runs its confidence detector across both split modes and seeds.
        pipeline["detectors"] = ["confidence"]
    known_results = open_results = rag_results = None
    if not options.skip_known:
        from ml.evaluation.known_classifier import run_known_classifier
        known_results, _, _ = run_known_classifier(pipeline, include_xgboost=options.include_xgboost)
    if not options.skip_open_set:
        from ml.evaluation.open_set_pipeline import run_open_set_evaluation
        open_results = run_open_set_evaluation(pipeline)
    if not options.skip_rag:
        from ml.evaluation.evaluate_rag_quality import evaluate_rag_quality
        rag_results = evaluate_rag_quality()
    update_results_doc(known_results, open_results, rag_results)
    result = {"known_classifier": known_results, "open_set": open_results, "rag_quality": rag_results}
    output = get_results_dir() / "comprehensive_benchmark_run.json"
    output.write_text(json.dumps(result, indent=2, default=str) + "\n", encoding="utf-8")
    return {"results_path": str(output), "known_classifier": known_results is not None,
            "open_set": open_results is not None, "rag_quality": rag_results is not None}


if __name__ == "__main__":
    print(json.dumps(run(), indent=2))
