class TestComputeKs:
    def test_identical_distributions_low_ks(self):
        """SYNTHETIC: KS statistic between two large same-distribution samples is small."""
        x = RNG.standard_normal(2000)
        y = RNG.standard_normal(2000)
        stat, pvalue = compute_ks(x, y)
        assert stat < 0.1, f"KS stat between same-dist samples too large: {stat}"
        assert pvalue > 0.01

    def test_clearly_different_distributions_high_ks(self):
        """SYNTHETIC: U(0,1) vs. N(5,0.1) must have KS statistic near 1."""
        ref = RNG.uniform(0, 1, 1000)
        cur = RNG.normal(5, 0.1, 1000)
        stat, pvalue = compute_ks(ref, cur)
        assert stat > 0.9, f"Expected KS~1 for disjoint distributions, got {stat}"
        assert pvalue < 1e-10

    def test_returns_tuple_of_floats(self):
        """Return types must be (float, float)."""
        ref = RNG.standard_normal(100)
        cur = RNG.standard_normal(100)
        stat, pvalue = compute_ks(ref, cur)
        assert isinstance(stat, float)
        assert isinstance(pvalue, float)

    def test_empty_arrays_return_zero_one(self):
        """Edge case: empty arrays must return (0.0, 1.0) without raising."""
        stat, pvalue = compute_ks([], [1.0, 2.0])
        assert stat == 0.0
        assert pvalue == 1.0


