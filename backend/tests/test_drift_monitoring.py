class TestEvaluateDriftThresholds:
    def test_very_tight_threshold_triggers_drift(self):
        """SYNTHETIC: even a tiny shift triggers drift when thresholds are near-zero."""
        ref, cur = _identical_gaussian(n=400, d=2)
        # Force any PSI > 0 to count as drift
        result = evaluate_drift(ref, cur, psi_threshold=0.0, ks_threshold=0.0)
        # With threshold=0 any nonzero PSI is drift; we just check the structure
        assert isinstance(result["drift_detected"], bool)

    def test_very_loose_threshold_suppresses_drift(self):
        """SYNTHETIC: even a large shift is suppressed by an enormous threshold."""
        ref, cur = _shifted_gaussian(shift=5.0, n=400, d=2)
        result = evaluate_drift(ref, cur, psi_threshold=1000.0, ks_threshold=1.0)
        assert result["drift_detected"] is False

    def test_threshold_values_echoed_in_result(self):
        """Thresholds passed explicitly must appear in result['thresholds']."""
        ref = RNG.standard_normal((100, 2))
        cur = RNG.standard_normal((100, 2))
        result = evaluate_drift(ref, cur, psi_threshold=0.1, ks_threshold=0.05,
                                prediction_psi_threshold=0.3)
        assert result["thresholds"]["psi"] == pytest.approx(0.1)
        assert result["thresholds"]["ks"] == pytest.approx(0.05)
        assert result["thresholds"]["prediction_psi"] == pytest.approx(0.3)


