class TestEvaluateDriftFeatureDrift:
    def test_psi_drift_detected_on_shifted_distribution(self):
        """SYNTHETIC: 5-sigma shift must trigger drift_detected=True via PSI."""
        ref, cur = _shifted_gaussian(shift=5.0, n=600, d=2)
        result = evaluate_drift(
            ref, cur,
            feature_names=["bytes", "packets"],
            psi_threshold=0.25,
            ks_threshold=0.15,
        )
        assert result["drift_detected"] is True, "Expected drift for 5-sigma shift"
        assert result["summary"]["drifted_feature_count"] > 0
        assert len(result["summary"]["drifted_features"]) > 0

    def test_ks_drift_detected_on_different_shape(self):
        """SYNTHETIC: uniform vs. normal (different shapes) must trigger drift via KS."""
        ref, cur = _uniform_vs_normal(n=600)
        result = evaluate_drift(
            ref, cur,
            feature_names=["flow_duration"],
            psi_threshold=0.25,
            ks_threshold=0.05,  # tight threshold to ensure detection
        )
        assert result["drift_detected"] is True

    def test_per_feature_dict_structure(self):
        """Each feature entry must contain psi, ks_statistic, ks_pvalue, drifted."""
        ref, cur = _shifted_gaussian(n=200, d=2)
        result = evaluate_drift(ref, cur, feature_names=["f0", "f1"])
        for fname in ("f0", "f1"):
            entry = result["features"][fname]
            assert "psi" in entry
            assert "ks_statistic" in entry
            assert "ks_pvalue" in entry
            assert "drifted" in entry

    def test_auto_generated_feature_names(self):
        """When feature_names is None, names default to feature_0, feature_1, ..."""
        ref = RNG.standard_normal((100, 3))
        cur = RNG.standard_normal((100, 3))
        result = evaluate_drift(ref, cur)
        assert "feature_0" in result["features"]
        assert "feature_2" in result["features"]


