class TestEvaluateDriftPredictionShift:
    def test_prediction_shift_detected(self):
        """SYNTHETIC: predictions shift from low (~0.1) to high (~0.9) → shift detected."""
        # SYNTHETIC: not real model outputs; purely numerical arrays for unit testing
        ref_preds = RNG.uniform(0.0, 0.2, 500)   # all near 0
        cur_preds = RNG.uniform(0.8, 1.0, 500)   # all near 1
        ref_x = RNG.standard_normal((500, 2))
        cur_x = RNG.standard_normal((500, 2))
        result = evaluate_drift(
            ref_x, cur_x,
            reference_predictions=ref_preds,
            current_predictions=cur_preds,
            prediction_psi_threshold=0.25,
        )
        assert result["prediction_shift"] is not None
        assert result["prediction_shift"]["drifted"] is True, (
            "Expected prediction distribution shift to be detected"
        )
        assert result["drift_detected"] is True

    def test_no_prediction_shift_when_similar(self):
        """SYNTHETIC: predictions from same distribution → prediction_shift.drifted=False."""
        ref_preds = RNG.uniform(0.4, 0.6, 500)
        cur_preds = RNG.uniform(0.4, 0.6, 500)
        ref_x = RNG.standard_normal((500, 2))
        cur_x = RNG.standard_normal((500, 2))
        result = evaluate_drift(
            ref_x, cur_x,
            reference_predictions=ref_preds,
            current_predictions=cur_preds,
            prediction_psi_threshold=0.25,
        )
        assert result["prediction_shift"] is not None
        assert result["prediction_shift"]["drifted"] is False

    def test_no_predictions_gives_none_shift(self):
        """When predictions are not supplied, prediction_shift must be None."""
        ref = RNG.standard_normal((200, 2))
        cur = RNG.standard_normal((200, 2))
        result = evaluate_drift(ref, cur)
        assert result["prediction_shift"] is None


