class TestComputePsi:
    def test_identical_data_psi_near_zero(self):
        """SYNTHETIC: PSI of a signal against itself must be ~0."""
        x = RNG.standard_normal(1000)
        psi = compute_psi(x, x)
        assert psi < 0.01, f"Expected PSI~0 for identical data, got {psi}"

    def test_highly_shifted_psi_exceeds_threshold(self):
        """SYNTHETIC: 5-sigma mean shift must produce PSI >> 0.25 (severe drift)."""
        ref = RNG.standard_normal(1000)
        cur = RNG.standard_normal(1000) + 10.0  # 10-sigma shift
        psi = compute_psi(ref, cur)
        assert psi > 0.25, f"Expected high PSI for extreme shift, got {psi}"

    def test_psi_nonnegative(self):
        """SYNTHETIC: PSI must always be >= 0."""
        ref = RNG.uniform(0, 1, 500)
        cur = RNG.uniform(0.1, 1.1, 500)
        psi = compute_psi(ref, cur)
        assert psi >= 0.0

    def test_empty_arrays_return_zero(self):
        """Edge case: empty arrays should return 0 without raising."""
        assert compute_psi([], [1.0, 2.0]) == 0.0
        assert compute_psi([1.0, 2.0], []) == 0.0

    def test_constant_reference_no_drift(self):
        """SYNTHETIC: constant reference where current matches → PSI == 0."""
        ref = np.ones(100)
        cur = np.ones(100)
        assert compute_psi(ref, cur) == 0.0

    def test_constant_reference_drift_detected(self):
        """SYNTHETIC: constant reference where current differs → PSI > 0."""
        ref = np.ones(100)
        cur = np.zeros(100)
        assert compute_psi(ref, cur) > 0.0


