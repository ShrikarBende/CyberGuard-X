"""
Tests for feature and prediction drift monitoring (PSI + KS).

All reference and current data in every test are SYNTHETIC (programmatically
generated for unit-testing purposes). None of these arrays represent real
network traffic or labelled dataset rows.
"""
from __future__ import annotations

import numpy as np
import pytest

from ml.models.drift import compute_psi, compute_ks, evaluate_drift


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

RNG = np.random.default_rng(42)


def _identical_gaussian(n: int = 500, d: int = 4) -> tuple[np.ndarray, np.ndarray]:
    """Return two samples drawn from the exact same standard-normal distribution.

    SYNTHETIC: values are generated by a seeded PRNG; no real data involved.
    """
    ref = RNG.standard_normal((n, d))
    cur = RNG.standard_normal((n, d))
    return ref, cur


def _shifted_gaussian(shift: float = 5.0, n: int = 500, d: int = 4) -> tuple[np.ndarray, np.ndarray]:
    """Return reference (N(0,1)) and current (N(shift,1)) arrays for each feature.

    SYNTHETIC: a 5-sigma mean shift guarantees measurable drift under any
    reasonable PSI/KS threshold without touching real data.
    """
    ref = RNG.standard_normal((n, d))
    cur = RNG.standard_normal((n, d)) + shift
    return ref, cur


def _uniform_vs_normal(n: int = 500) -> tuple[np.ndarray, np.ndarray]:
    """Return reference drawn from U(0,1) and current from N(0.5, 0.15).

    SYNTHETIC: different distribution shapes (uniform vs. unimodal bell curve).
    """
    ref = RNG.uniform(0, 1, (n, 1))
    cur = RNG.normal(0.5, 0.15, (n, 1))
    return ref, cur


